"""Recover a narrowly supported missing tuplet from independent printed evidence.

The current homr duration vocabulary cannot express a 2:3 duplet. Do not invent
one merely to fill an underfull bar: require a printed 2 near the staff, a
unique adjacent equal-value pair under it, and exact agreement with the meter.
The same independent evidence can recover a missed 5:4 quintuplet. Only
single-staff voices are changed. A narrow polyphonic case can be rebuilt as
independent voice blocks only when every voice then exactly covers the meter.

Glyph rasters are from Bravura and Leipzig (OFL-1.1), generated by
bench/generate_tuplet_templates.py; see their licenses in public/. Template
similarities are shape scores, not probabilities of a correct transcription.
"""
import base64
import copy
from fractions import Fraction
import json
import math
import itertools
from pathlib import Path
import re
import xml.etree.ElementTree as ET
from decimal import Decimal

import cv2
import numpy as np
from tuplet_glyphs import classify_glyph

_BANK = None
_AT = re.compile(r'-p(\d+)-(\d+)-(\d+)$')


def _templates():
    global _BANK
    if _BANK is None:
        bank = json.loads(Path(__file__).with_name('tuplet_templates.json').read_text())
        _BANK = [(item['number'], np.frombuffer(base64.b64decode(item['raster']), np.uint8)
                  .reshape(32, 24).astype(np.float32)/255) for item in bank]
    return _BANK


def read_tuplet_marks(image, boxes):
    gray = cv2.cvtColor(image, cv2.COLOR_BGR2GRAY) if image.ndim == 3 else image
    result = []
    for staff, (left, top, right, bottom, *_) in enumerate(boxes):
        unit = (bottom-top)/4
        if unit < 2:
            continue
        for region in ('above', 'below', 'staff'):
            # Tuplet figures may overlap a staff line for low/high ledger notes.
            # Remove long horizontal ink, then bridge only its narrow vertical gaps.
            a, b = ((top-4*unit, top-.3*unit) if region == 'above' else
                    (bottom+.3*unit, bottom+4*unit) if region == 'below' else
                    (top-6*unit, bottom+6*unit))
            x0, x1 = max(0, int(left)), min(gray.shape[1], int(right))
            y0, y1 = max(0, round(a)), min(gray.shape[0], round(b))
            if x1 <= x0 or y1 <= y0:
                continue
            ink = (gray[y0:y1, x0:x1] < 160).astype(np.uint8)
            if region == 'staff':
                lines = cv2.morphologyEx(ink, cv2.MORPH_OPEN, np.ones((1, max(12, round(unit*8))), np.uint8))
                fragments = ink-lines
                _, components, bounds, _ = cv2.connectedComponentsWithStats(fragments)
                eligible = np.ones(len(bounds), np.uint8)
                eligible[0] = 0
                # Bridge digit fragments without connecting them to a nearby
                # beam/stem. These components already exceed the final glyph
                # size limits, so cannot be part of a supported complete figure.
                eligible[(bounds[:, 2] > 2.3*unit) | (bounds[:, 3] > 1.9*unit)] = 0
                ink = cv2.morphologyEx(eligible[components], cv2.MORPH_CLOSE, np.ones((3, 1), np.uint8))
            _, labels, stats, _ = cv2.connectedComponentsWithStats(ink)
            for label, (x, y, width, height, area) in enumerate(stats[1:], 1):
                if not (.75*unit <= height <= 1.9*unit and .3 <= width/height <= 1.2
                        and .15 <= area/(width*height) <= .8):
                    continue
                # A figure inside a multi-digit tempo/label is not a tuplet.
                # Check raw neighbouring ink too: 1 and 0 are intentionally
                # outside the classifier's accepted tuplet vocabulary.
                neighbours = [other for other in stats[1:] if (other != stats[label]).any()
                              and .65*height <= other[3] <= 1.5*height
                              and .2 <= other[2]/other[3] <= 1.3
                              and min(y+height, other[1]+other[3])-max(y, other[1]) >= .5*height
                              and -.1*unit <= max(x, other[0])-min(x+width, other[0]+other[2]) <= .5*unit]
                if neighbours:
                    continue
                # Isolate this connected glyph so nearby beams cannot improve its score.
                glyph = (labels[y:y+height, x:x+width] == label).astype(np.float32)
                glyph = cv2.resize(glyph, (24, 32), interpolation=cv2.INTER_AREA)
                reading = classify_glyph(glyph)
                number = reading['number']
                if number is None:
                    continue
                mark = {'staff': staff, 'number': number, 'x': float(round(x0+x+width/2, 2)),
                               'y': round(y0+y+height/2, 2),
                               'box': [x0+int(x), y0+int(y), x0+int(x+width), y0+int(y+height)],
                               'classifier': 'TupletGlyphCNN', 'rawLogit': round(reading['score'], 4),
                               'logitMargin': round(reading['margin'], 4)}
                duplicate = next((old for old in result if old['staff'] == staff and old['number'] == number
                                  and abs(old['x']-mark['x']) < .3*unit and abs(old['y']-mark['y']) < .3*unit), None)
                if duplicate is None:
                    result.append(mark)
                elif mark['logitMargin'] > duplicate['logitMargin']:
                    duplicate.update(mark)
    # Wide ledger-note searches can see figures belonging to a neighbouring
    # staff. Retain the nearest staff's claim instead of manufacturing two
    # competing readings of the same ink in a piano system.
    return [mark for mark in result if mark['staff'] == min(range(len(boxes)),
            key=lambda i: max(boxes[i][1]-mark['y'], mark['y']-boxes[i][3], 0))]


def _point(note):
    match = _AT.search(note.get('id', ''))
    return tuple(map(int, match.groups())) if match else None


def _scale_part(part, factor):
    if factor == 1:
        return
    for node in part.iter():
        if node.tag in ('duration', 'divisions', 'offset') and node.text:
            node.text = str(Decimal(node.text)*factor)
        for name in ('attack', 'release'):
            if name in node.attrib:
                node.set(name, str(Decimal(node.get(name))*factor))


def _voice_groups(measure):
    groups = {}
    for note in measure.findall('note'):
        if note.find('grace') is not None or note.find('chord') is not None:
            return {}
        key = (note.findtext('voice', '1'), note.findtext('staff', '1'))
        groups.setdefault(key, []).append(note)
    if len({key[0] for key in groups}) != len(groups):
        return {}  # Cross-staff voices require their own timing/beam treatment.
    return groups


def _polyphonic_candidates(score, sources):
    """Solve a printed group within one voice, not the sum of both staves.

    homr may interleave voices and fabricate single-note triplet brackets when
    it cannot represent a printed 5. Consider removing only those malformed
    one-note 3:2 brackets; require one unique source-supported solution and exact
    full-meter coverage by EVERY voice. Do not move directions or implicit gaps.
    """
    proposals = []
    for part in score.findall('part'):
        divisions, meter = 1, None
        for index, measure in enumerate(part.findall('measure'), 1):
            for attributes in measure.findall('attributes'):
                divisions = int(attributes.findtext('divisions', str(divisions)))
                for time in attributes.findall('time'):
                    if time.findtext('beats') and time.findtext('beat-type'):
                        meter = (time.findtext('beats'), time.findtext('beat-type'))
            if (not meter or measure.find('backup') is None or measure.get('implicit') == 'yes'
                    or any(child.tag not in ('note', 'backup', 'attributes', 'print', 'barline') for child in measure)):
                continue
            groups = _voice_groups(measure)
            if len(groups) < 2:
                continue
            expected = Fraction(sum(map(int, meter[0].split('+')))*4, int(meter[1]))
            candidates = []
            for key, notes in groups.items():
                if any(sum((Fraction(n.findtext('duration', '0'))/divisions for n in other), Fraction()) != expected
                       for other_key, other in groups.items() if other_key != key):
                    continue
                orphans = [n for n in notes if n.findtext('time-modification/actual-notes') == '3'
                           and n.findtext('time-modification/normal-notes') == '2'
                           and n.find('notations/tuplet[@type="start"]') is not None
                           and n.find('notations/tuplet[@type="stop"]') is not None
                           and n.findtext('type') in ('eighth', '16th', '32nd') and n.find('dot') is None]
                if len(orphans) > 3:
                    continue
                for size in range(len(orphans)+1):
                    for stripped in itertools.combinations(orphans, size):
                        fake = ET.Element('score-partwise')
                        fp = ET.SubElement(fake, 'part', id=part.get('id'))
                        fm = ET.SubElement(fp, 'measure', number=measure.get('number', str(index)))
                        attrs = ET.SubElement(fm, 'attributes')
                        ET.SubElement(attrs, 'divisions').text = str(divisions)
                        time = ET.SubElement(attrs, 'time')
                        ET.SubElement(time, 'beats').text = meter[0]
                        ET.SubElement(time, 'beat-type').text = meter[1]
                        extra = []
                        for original in notes:
                            node = copy.deepcopy(original)
                            if original in stripped:
                                current = Fraction(original.findtext('duration'))/divisions
                                target = current*Fraction(3, 2)
                                if (target*divisions).denominator != 1:
                                    break
                                extra.append({'id': original.get('id'), 'fromQ': str(current), 'toQ': str(target),
                                              'fromRatio': '2/3', 'type': original.findtext('type')})
                                node.find('duration').text = str(int(target*divisions))
                                node.remove(node.find('time-modification'))
                                for notation in node.findall('notations'):
                                    for mark in list(notation.findall('tuplet')):
                                        notation.remove(mark)
                            fm.append(node)
                        else:
                            for candidate in tuplet_candidates(fake, sources):
                                # An orphan removed outside the printed group is
                                # a separate edit; never overwrite a group edit.
                                if any(e['id'] in candidate['notes'] for e in extra):
                                    continue
                                candidate.update(measure=index, voice=key[0], staff=key[1],
                                    currentQ=str(sum((Fraction(n.findtext('duration'))/divisions for n in notes), Fraction())),
                                    rebuildVoices=[{'voice': k[0], 'staff': k[1], 'notes': [n.get('id') for n in v]}
                                                   for k, v in groups.items()])
                                candidate['edits'].extend(extra)
                                candidates.append(candidate)
            if len(candidates) == 1:
                proposals.append(candidates[0])
    return proposals


def tuplet_candidates(score, sources):
    pages = {source['page']: source for source in sources}
    proposals = _polyphonic_candidates(score, sources)
    for part in score.findall('part'):
        divisions, meter = 1, None
        for index, measure in enumerate(part.findall('measure'), 1):
            for attributes in measure.findall('attributes'):
                divisions = int(attributes.findtext('divisions', str(divisions)))
                for time in attributes.findall('time'):
                    beats, unit = time.findtext('beats'), time.findtext('beat-type')
                    if beats and unit:
                        meter = Fraction(sum(map(int, beats.split('+')))*4, int(unit))
            notes = [note for note in measure.findall('note') if note.find('grace') is None]
            if not meter or not notes or measure.find('backup') is not None or measure.find('forward') is not None:
                continue
            if (measure.get('implicit') == 'yes' or any(n.find('chord') is not None for n in notes)
                    or len({(n.findtext('voice', '1'), n.findtext('staff', '1')) for n in notes}) != 1):
                continue
            total = sum((Fraction(int(n.findtext('duration', '0')), divisions) for n in notes), Fraction())
            candidates, runs, pending = [], {}, []
            for note in notes:
                marks = note.findall('notations/tuplet')
                if any(mark.get('type') == 'start' for mark in marks):
                    pending = []
                if note.find('time-modification') is not None:
                    pending.append(note)
                if any(mark.get('type') == 'stop' for mark in marks):
                    for member in pending:
                        runs[id(member)] = pending
                    pending = []
            groups = [(notes[i:i+count], count, normal) for count, normal in ((2, 3), (3, 2), (5, 4))
                      for i in range(len(notes)-count+1)]
            for selected, count, normal in groups:
                first, second = selected[0], selected[-1]
                if any(n.find('dot') is not None for n in selected):
                    continue
                if first.findtext('type') not in ('eighth', '16th', '32nd') or any(n.findtext('type') != first.findtext('type') for n in selected):
                    continue
                written = {'eighth': Fraction(1, 2), '16th': Fraction(1, 4), '32nd': Fraction(1, 8)}[first.findtext('type')]
                affected = selected
                if any(n.find('time-modification') is not None for n in affected):
                    # The unsupported 2 can also be guessed as a 3, pulling the next
                    # note into a fabricated triplet. Require the complete marked
                    # three-note run and check its replacement against the meter.
                    run = runs.get(id(first), [])
                    if count == 2:
                        if len(run) != 3 or runs.get(id(second)) is not run:
                            continue
                        if any(n.findtext('time-modification/actual-notes') != '3'
                               or n.findtext('time-modification/normal-notes') != '2'
                               or n.findtext('type') != first.findtext('type') or n.find('dot') is not None for n in run):
                            continue
                        affected = run
                    elif any(id(member) not in {id(n) for n in selected}
                             for n in selected for member in runs.get(id(n), [n])):
                        continue
                edits = []
                for note in affected:
                    current = Fraction(int(note.findtext('duration', '0')), divisions)
                    ratio = Fraction(int(note.findtext('time-modification/normal-notes', '1')),
                                     int(note.findtext('time-modification/actual-notes', '1')))
                    if current != written*ratio:
                        break
                    target = written*Fraction(normal, count) if note in selected else written
                    edits.append({'id': note.get('id'), 'fromQ': str(current), 'toQ': str(target),
                                  'fromRatio': str(ratio), 'type': note.findtext('type')})
                if len(edits) != len(affected) or total+sum((Fraction(e['toQ'])-Fraction(e['fromQ']) for e in edits), Fraction()) != meter:
                    continue
                if all(edit['fromQ'] == edit['toQ'] for edit in edits):
                    continue
                a, b = _point(first), _point(second)
                if not a or not b or a[0] != b[0] or b[1] <= a[1]:
                    continue
                page = pages.get(a[0])
                if not page or not page.get('layout'):
                    continue
                boxes = page['layout']
                staff = min(range(len(boxes)), key=lambda i: max(boxes[i][1]-a[2], a[2]-boxes[i][3], 0))
                if staff != min(range(len(boxes)), key=lambda i: max(boxes[i][1]-b[2], b[2]-boxes[i][3], 0)):
                    continue
                for mark in page.get('tuplets', []):
                    unit = (boxes[staff][3]-boxes[staff][1])/4
                    if (mark['staff'] == staff and mark.get('number', 2) == count and a[1] <= mark['x'] <= b[1]
                            and abs(mark['x']-(a[1]+b[1])/2) <= max(unit, .35*(b[1]-a[1]))):
                        candidates.append((selected, count, normal, mark, a[0], written, edits))
            if len(candidates) == 1:
                selected, count, normal, mark, page, duration, edits = candidates[0]
                proposals.append({'part': part.get('id'), 'measure': index,
                    'number': measure.get('number'), 'kind': 'printed-tuplet', 'actual': count, 'normal': normal,
                    'notes': [note.get('id') for note in selected], 'page': page, 'evidence': mark,
                    'currentQ': str(total), 'expectedQ': str(meter), 'noteQ': str(duration),
                    'edits': edits,
                    'options': [f'tuplet-{count}-{normal}', 'keep-and-review']})
    return proposals


def apply_tuplet(score, proposal):
    """Apply one explicit choice, rejecting stale candidates. No pitch edits.

    Candidates alone never change a score. Callers can use this to evaluate an
    automatic policy against ground truth or apply a user's confirmed choice.
    """
    part = next((p for p in score.findall('part') if p.get('id') == proposal['part']), None)
    if part is None or not 1 <= proposal['measure'] <= len(part.findall('measure')):
        raise ValueError('Duplet part or measure no longer exists')
    measure = part.findall('measure')[proposal['measure']-1]
    notes = [n for n in measure.findall('note') if n.get('id') in proposal['notes']]
    if len(notes) != proposal['actual'] or [n.get('id') for n in notes] != proposal['notes']:
        raise ValueError('Duplet notes no longer exist in order')
    divisions, meter = 1, None
    for current in part.findall('measure')[:proposal['measure']]:
        for attributes in current.findall('attributes'):
            divisions = int(attributes.findtext('divisions', str(divisions)))
            for time in attributes.findall('time'):
                beats, unit = time.findtext('beats'), time.findtext('beat-type')
                if beats and unit:
                    meter = Fraction(sum(map(int, beats.split('+')))*4, int(unit))
    if meter != Fraction(proposal['expectedQ']):
        raise ValueError('Duplet meter has changed; recheck the source')
    edits = proposal['edits']
    changed = []
    for edit in edits:
        note = next((n for n in measure.findall('note') if n.get('id') == edit['id']), None)
        if note is None:
            raise ValueError('Duplet candidate is stale; recheck the source')
        ratio = Fraction(int(note.findtext('time-modification/normal-notes', '1')),
                         int(note.findtext('time-modification/actual-notes', '1')))
        if (note.find('dot') is not None or note.findtext('type') != edit['type'] or str(ratio) != edit['fromRatio']
                or Fraction(int(note.findtext('duration', '0')), divisions) != Fraction(edit['fromQ'])):
            raise ValueError('Duplet candidate is stale; recheck the source')
        changed.append((note, edit))
    voice_groups = _voice_groups(measure) if proposal.get('rebuildVoices') else None
    if voice_groups is not None:
        specification = [{'voice': k[0], 'staff': k[1], 'notes': [n.get('id') for n in v]} for k, v in voice_groups.items()]
        if specification != proposal['rebuildVoices'] or any(child.tag not in
                ('note', 'backup', 'attributes', 'print', 'barline') for child in measure):
            raise ValueError('Duplet voices have changed; recheck the source')
        target_key = (proposal['voice'], proposal['staff'])
        timed_notes = voice_groups[target_key]
        for key, group in voice_groups.items():
            current = sum((Fraction(n.findtext('duration', '0'))/divisions for n in group), Fraction())
            delta = sum((Fraction(e['toQ'])-Fraction(e['fromQ']) for e in edits), Fraction()) if key == target_key else 0
            if current+delta != meter:
                raise ValueError('Duplet voice no longer covers the complete meter')
    else:
        timed_notes = measure.findall('note')
    total = sum((Fraction(int(n.findtext('duration', '0')), divisions) for n in timed_notes
                 if n.find('grace') is None and n.find('chord') is None), Fraction())
    if str(total) != proposal['currentQ']:
        raise ValueError('Duplet measure has changed; recheck the source')
    factor = math.lcm(*[(Fraction(edit['toQ'])*divisions).denominator for edit in edits])
    _scale_part(part, factor)
    for note, edit in changed:
        note.find('duration').text = str(int(Fraction(edit['toQ'])*divisions*factor))
        for modification in list(note.findall('time-modification')):
            note.remove(modification)
        for notation in note.findall('notations'):
            for tuplet in list(notation.findall('tuplet')):
                notation.remove(tuplet)
    for index, note in enumerate(notes):
        modification = ET.Element('time-modification')
        ET.SubElement(modification, 'actual-notes').text = str(proposal['actual'])
        ET.SubElement(modification, 'normal-notes').text = str(proposal['normal'])
        # MusicXML requires time-modification before staff/beam/notations.
        tail = next((i for i, child in enumerate(note) if child.tag in
                     ('stem', 'notehead', 'notehead-text', 'staff', 'beam', 'notations', 'lyric', 'play', 'listen')), len(note))
        note.insert(tail, modification)
        notation = note.find('notations')
        if notation is None:
            notation = ET.SubElement(note, 'notations')
        if index in (0, len(notes)-1):
            ET.SubElement(notation, 'tuplet', type='start' if index == 0 else 'stop', number='1')
    if voice_groups is not None:
        header, tail = [], []
        for child in measure:
            if child.tag in ('attributes', 'print') or child.tag == 'barline' and child.get('location') == 'left':
                header.append(child)
            elif child.tag == 'barline':
                tail.append(child)
        measure[:] = header
        for index, group in enumerate(voice_groups.values()):
            if index:
                backup = ET.SubElement(measure, 'backup')
                ET.SubElement(backup, 'duration').text = str(int(meter*divisions*factor))
            measure.extend(group)
        measure.extend(tail)
    return proposal


def repair_tuplets(score, sources):
    """Experimental policy, opt-in until validated on held-out scores."""
    changes = []
    for candidate in tuplet_candidates(score, sources):
        changes.append(apply_tuplet(score, candidate))
    return changes
